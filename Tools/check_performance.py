#!/usr/bin/env python3
"""Check the actual Device performance module with simulated MCU registers.

Run with Python 3.6+ and a host GCC-compatible C++ compiler:
    python Tools/check_performance.py [--cxx C:/mingw64/bin/g++.exe]

The tests cover duration/frequency arithmetic, resets, counter wrapping, RTOS
memory diagnostics, and compile-time removal. They do not measure STM32
execution time, real stack use, or cache effects.
All headers, executables, and object files generated by this check are temporary.
"""

