def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--cxx", default=shutil.which("g++") or "C:/mingw64/bin/g++.exe")
    args = parser.parse_args()
    root = args.root.resolve()
    include_directory = root / "User/Device/Inc"
    source = root / "User/Device/Src/dvc_performance.cpp"
    compiler = shutil.which(args.cxx) or args.cxx
    compiler_directory = Path(compiler).resolve().parent
    nm = next((str(path) for path in
               (compiler_directory / "nm.exe", compiler_directory / "nm")
               if path.is_file()), shutil.which("nm"))

    with tempfile.TemporaryDirectory(prefix="performance_check_") as directory:
        temporary = Path(directory)
        enabled = temporary / "enabled"
        disabled = temporary / "disabled"
        enabled.mkdir()
        disabled.mkdir()
        for stub_directory in (enabled, disabled):
            (stub_directory / "config.h").write_text(CONFIG_HEADER, encoding="utf-8")
        (enabled / "main.h").write_text(MAIN_HEADER, encoding="utf-8")
        (enabled / "FreeRTOS.h").write_text(FREERTOS_HEADER, encoding="utf-8")
        (enabled / "task.h").write_text(TASK_HEADER, encoding="utf-8")
        enabled_harness = enabled / "check.cpp"
        enabled_harness.write_text(ENABLED_HARNESS, encoding="utf-8")
        disabled_harness = disabled / "check.cpp"
        disabled_harness.write_text(DISABLED_HARNESS, encoding="utf-8")

        for tcm in (0, 1):
            executable = enabled / ("tcm%d.exe" % tcm)
            command = [compiler, "-std=c++11", "-O0", "-Wall", "-Wextra", "-Werror",
                       "-DPERFORMANCE_TEST_ENABLE=1", "-DEKF_USE_TCM=%d" % tcm,
                       "-I" + str(enabled), "-I" + str(include_directory),
                       str(source), str(enabled_harness), "-o", str(executable)]
            subprocess.check_call(command)
            subprocess.check_call([str(executable)])
        print("PASS: duration averages/extrema, reset, clock changes, and 64-bit accumulation.")
        print("PASS: frequency baseline, averages/extrema, zero interval, offline gaps, and counter wraps.")
        print("PASS: measurement macros, cache/TCM metadata, and deadline counting.")
        print("PASS: bound task stack bytes, kernel heap minima, and allocation-free memory polling.")
        print("PASS: optional online-task binding, NULL unbinding, stack bytes, and 1000 Hz event object.")
        print("PASS: immediate/1-second polling, missing handles, tick wrap, and saturated sample counts.")

        # This include directory deliberately contains no MCU or RTOS headers.
        # Both the module and its client must build without those definitions.
        base_command = [compiler, "-std=c++11", "-O0", "-Wall", "-Wextra", "-Werror",
                        "-DPERFORMANCE_TEST_ENABLE=0", "-I" + str(disabled),
                        "-I" + str(include_directory)]
        executable = disabled / "disabled.exe"
        subprocess.check_call(base_command + [str(source), str(disabled_harness),
                                              "-o", str(executable)])
        subprocess.check_call([str(executable)])
        # The public disabled macros must also remain valid in C callers.
        subprocess.check_call([compiler, "-x", "c", "-std=c99", "-Wall", "-Wextra",
                               "-Werror", "-DPERFORMANCE_TEST_ENABLE=0",
                               "-I" + str(disabled), "-I" + str(include_directory),
                               "-fsyntax-only", str(disabled_harness)])
        print("PASS: disabled C/C++ callers need no MCU/RTOS headers and do not evaluate macro arguments.")
        if nm:
            module_object = disabled / "module.o"
            subprocess.check_call(base_command + ["-c", str(source), "-o", str(module_object)])
            symbols = subprocess.check_output([nm, "--defined-only",
                                               str(module_object)], universal_newlines=True)
            # MinGW COFF objects retain empty section labels and a compiler
            # identification section even when the translation unit is empty.
            metadata_sections = {".text", ".data", ".bss", ".rdata$zzz"}
            code_or_data_symbols = [line for line in symbols.splitlines()
                                    if line.strip() and line.split()[-1] not in metadata_sections]
            if code_or_data_symbols:
                raise AssertionError("Disabled module still defines symbols:\n" +
                                     "\n".join(code_or_data_symbols))
            print("PASS: disabled module defines no code or data symbols, including private task state.")
        else:
            print("SKIP: nm unavailable; disabled external-symbol check was not run.")
